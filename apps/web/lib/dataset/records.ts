import type { InteractionSession } from "@captchalab/captcha-core";
import { analyzeSession } from "@/lib/behavior/analysis";
import { classify, type Classification } from "@/lib/behavior/classifier";
import { SIGNALS_BY_CAPTCHA } from "@/lib/behavior/signal-catalog";
import type { BehaviorContext, BehavioralVector, SyntheticMeta } from "@/lib/behavior/types";
import { generateChallenge, type ChallengeDefinition } from "@/lib/research/definition";
import { FormatError } from "@/lib/research/safe";

/**
 * The label a PERSON gave a session. It is metadata about the sample, never an output of the classifier and never an
 * input to it: no function in this module reads a classification to decide a label.
 *   human      the user states that a person made this interaction
 *   synthetic  the session was generated (by CaptchaLab, or the user states so)
 *   unknown    nobody stated anything (the default for a recorded session)
 */
export const GROUND_TRUTH_LABELS = ["human", "synthetic", "unknown"] as const;
export type GroundTruthLabel = (typeof GROUND_TRUTH_LABELS)[number];

export const isLabel = (v: unknown): v is GroundTruthLabel => typeof v === "string" && (GROUND_TRUTH_LABELS as readonly string[]).includes(v);

export const DATASET_SCHEMA = "captchalab-labeled-dataset" as const;
export const DATASET_VERSION = 1 as const;
/** At most this many records in the in-memory dataset. */
export const MAX_DATASET_RECORDS = 500;
/** At most this many events across the dataset, so memory and the export file stay bounded. */
export const MAX_DATASET_EVENTS = 300_000;

/**
 * Where a record came from, kept apart from its label. `type` says how the session was made; `imported` says it came
 * from a file (a file proves nothing about who made it).
 */
export interface RecordSource {
  type: "recorded" | "synthetic";
  imported: boolean;
  /** Synthetic records only: the profile, generator version and seed that make the session. */
  synthetic?: SyntheticMeta;
  /** Imported synthetic records only: whether the session was regenerated and matched. */
  provenanceChecked?: boolean;
}

/** What a file claimed about a record. Shown as information only; the current values are always recomputed. */
export interface ImportedClaims {
  features?: { version: string; sourceSchema: string; values: Readonly<Record<string, number | null>> };
  classifier?: { version: string; result: string };
}

export interface DatasetRecord {
  id: string;
  definition: ChallengeDefinition;
  source: RecordSource;
  label: GroundTruthLabel;
  context: BehaviorContext;
  passed?: boolean;
  /** Plain text, up to 200 characters. */
  note: string;
  session: InteractionSession;
  claims?: ImportedClaims;
}

/** What is derived from a record: its signals and the CURRENT classifier's reading. Recomputed, never stored. */
export interface RecordAnalysis {
  vector: BehavioralVector;
  classification: Classification;
}

export function analyzeRecord(r: DatasetRecord): RecordAnalysis {
  const vector = analyzeSession(r.definition.captcha, generateChallenge(r.definition), r.session, r.context);
  return { vector, classification: classify(vector) };
}

/** Generated here and still unchanged: its label is fixed, so a careless edit cannot mislabel generated data. */
export const isLabelLocked = (r: Pick<DatasetRecord, "source">): boolean => r.source.type === "synthetic" && !r.source.imported;

const ID = /^[A-Za-z0-9_-]{1,40}$/;
export const isRecordId = (id: string): boolean => ID.test(id);

/** The first free id of the form d1, d2, ... */
export function freeId(records: readonly { id: string }[], taken: ReadonlySet<string> = new Set()): string {
  const used = new Set([...records.map((r) => r.id), ...taken]);
  let n = records.length + taken.size + 1;
  while (used.has(`d${n}`)) n++;
  return `d${n}`;
}

export const eventsIn = (records: readonly DatasetRecord[]): number => records.reduce((n, r) => n + r.session.events.length, 0);

export interface NewRecorded {
  definition: ChallengeDefinition;
  session: InteractionSession;
  context: BehaviorContext;
  passed?: boolean;
  note?: string;
}

/** A session recorded here. It starts as `unknown`: recording an interaction does not make it a human one. */
export function recordedRecord(input: NewRecorded): Omit<DatasetRecord, "id"> {
  return {
    definition: input.definition,
    source: { type: "recorded", imported: false },
    label: "unknown",
    context: input.context,
    ...(input.passed === undefined ? {} : { passed: input.passed }),
    note: input.note ?? "",
    session: input.session,
  };
}

export interface NewSynthetic {
  definition: ChallengeDefinition;
  session: InteractionSession;
  context: BehaviorContext;
  meta: SyntheticMeta;
  note?: string;
}

/** A session generated by CaptchaLab: labelled `synthetic`, with its provenance. */
export function syntheticRecord(input: NewSynthetic): Omit<DatasetRecord, "id"> {
  return {
    definition: input.definition,
    source: { type: "synthetic", imported: false, synthetic: input.meta },
    label: "synthetic",
    context: input.context,
    note: input.note ?? "",
    session: input.session,
  };
}

/** Adds a record, giving it a free local id. Bounded; never overwrites an existing record. */
export function appendRecord(records: readonly DatasetRecord[], draft: Omit<DatasetRecord, "id"> & { id?: string }): DatasetRecord[] {
  if (records.length >= MAX_DATASET_RECORDS) throw new FormatError("too-large", `a dataset holds at most ${MAX_DATASET_RECORDS} records`);
  if (eventsIn(records) + draft.session.events.length > MAX_DATASET_EVENTS) throw new FormatError("too-large", `a dataset holds at most ${MAX_DATASET_EVENTS} events in total`);
  const wanted = draft.id;
  const id = wanted !== undefined && isRecordId(wanted) && !records.some((r) => r.id === wanted) ? wanted : freeId(records);
  return [...records, { ...draft, id }];
}

export function removeRecord(records: readonly DatasetRecord[], id: string): DatasetRecord[] {
  return records.filter((r) => r.id !== id);
}

/** Changes only the label (metadata). The session, the source and the classifier are untouched. */
export function setLabel(records: readonly DatasetRecord[], id: string, label: GroundTruthLabel): DatasetRecord[] {
  if (!isLabel(label)) throw new FormatError("invalid", `"${String(label)}" is not a label (use ${GROUND_TRUTH_LABELS.join(", ")})`);
  const target = records.find((r) => r.id === id);
  if (!target) throw new FormatError("invalid", `no record "${id}"`);
  if (isLabelLocked(target)) throw new FormatError("invalid", "a session generated by CaptchaLab keeps the label synthetic");
  return records.map((r) => (r.id === id ? { ...r, label } : r));
}

export function setNote(records: readonly DatasetRecord[], id: string, note: string): DatasetRecord[] {
  if (note.length > 200) throw new FormatError("invalid", "a note is at most 200 characters");
  return records.map((r) => (r.id === id ? { ...r, note } : r));
}

// ------------------------------------------------------------------------------------------------- summary

export type CountMap = Readonly<Record<string, number>>;

export interface Completeness {
  signal: string;
  /** Records whose CAPTCHA reports this signal. */
  of: number;
  /** Of those, how many have a value (the rest are missing, never zero). */
  present: number;
}

export interface DatasetSummary {
  total: number;
  labels: Readonly<Record<GroundTruthLabel, number>>;
  sources: Readonly<Record<"recorded" | "synthetic" | "imported", number>>;
  captchas: CountMap;
  difficulties: CountMap;
  variants: CountMap;
  /** The CURRENT classifier's outputs, counted. Not accuracy and not agreement with the labels. */
  classifierOutputs: Readonly<Record<"human-like" | "synthetic-like" | "uncertain", number>>;
  completeness: Completeness[];
}

const bump = (m: Record<string, number>, k: string): void => {
  m[k] = (m[k] ?? 0) + 1;
};

export function summarizeDataset(records: readonly DatasetRecord[], analyses: ReadonlyMap<string, RecordAnalysis>): DatasetSummary {
  const labels: Record<GroundTruthLabel, number> = { human: 0, synthetic: 0, unknown: 0 };
  const sources = { recorded: 0, synthetic: 0, imported: 0 };
  const captchas: Record<string, number> = {};
  const difficulties: Record<string, number> = {};
  const variants: Record<string, number> = {};
  const outputs = { "human-like": 0, "synthetic-like": 0, uncertain: 0 };
  const present = new Map<string, { of: number; present: number }>();
  for (const r of records) {
    labels[r.label]++;
    sources[r.source.imported ? "imported" : r.source.type]++;
    bump(captchas, r.definition.captcha);
    bump(difficulties, r.definition.difficulty);
    bump(variants, `${r.definition.captcha}/${r.definition.variant}`);
    const a = analyses.get(r.id);
    if (!a) continue;
    outputs[a.classification.label]++;
    for (const signal of SIGNALS_BY_CAPTCHA[r.definition.captcha]) {
      const c = present.get(signal) ?? { of: 0, present: 0 };
      c.of++;
      if (a.vector.values[signal] !== null && a.vector.values[signal] !== undefined) c.present++;
      present.set(signal, c);
    }
  }
  return {
    total: records.length,
    labels,
    sources,
    captchas,
    difficulties,
    variants,
    classifierOutputs: outputs,
    completeness: [...present.entries()].map(([signal, c]) => ({ signal, ...c })).sort((a, b) => a.signal.localeCompare(b.signal)),
  };
}
