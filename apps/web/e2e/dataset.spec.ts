test("the page makes no evaluation claims: no accuracy, precision, recall, F1, ROC, AUC or percentages", async ({ page }) => {
  await fill(page);
  const text = (await page.locator("main").textContent()) ?? "";
  // The page says it computes no accuracy; what must never appear is a metric with a value, or a metric by name.
  expect(text).not.toMatch(/(accuracy|precision|recall|F1|ROC|AUC)\W{0,3}\d|\bprecision\b|\brecall\b|\bF1\b|\bROC\b|\bAUC\b|false.positive|confusion|\d\s*%/i);
  expect(text.toLowerCase()).not.toMatch(/correct classification|wrong classification/);
});

