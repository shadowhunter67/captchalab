test("export, clear, import: the same records, labels, sources and readings come back", async ({ page }) => {
  await fill(page);
  await page.getByTestId("ds-label-d1").selectOption("human");
  const snap = () => page.evaluate(() => ({
    rows: Array.from(document.querySelectorAll('[data-testid^="ds-row-"]')).map((r) => [r.getAttribute("data-testid"), (r.querySelector("select") as HTMLSelectElement).value, r.querySelector('[data-testid^="ds-classifier-"]')!.getAttribute("data-label")]),
    labels: ["human", "synthetic", "unknown"].map((l) => document.querySelector(`[data-testid="ds-count-label-${l}"]`)!.textContent),
    coverage: document.querySelector('[data-testid="ds-coverage"]')!.textContent,
  }));
  const before = await snap();

  const file = await download(page, () => page.getByTestId("ds-export").click());
  expect(file.name).toMatch(/^captchalab-dataset-\d{4}-\d{2}-\d{2}\.json$/);
  const json = JSON.parse(file.text) as { schema: string; version: number; records: { id: string; label: string; source: { type: string }; session: { startedAt: number }; features: { version: string }; classifier: { version: string } }[] };
  expect(json).toMatchObject({ schema: "captchalab-labeled-dataset", version: 1 });
  expect(json.records.map((r) => [r.id, r.label, r.source.type])).toEqual([["d1", "human", "recorded"], ["d2", "synthetic", "synthetic"]]);
  expect(json.records.every((r) => r.session.startedAt === 0 && r.features.version === "behavior-signals@1" && r.classifier.version === "behavioral-baseline@1")).toBe(true);
  await expect(page.getByTestId("ds-unsaved")).toHaveCount(0); // exported: nothing unsaved

  await page.getByTestId("ds-clear").click();
  await page.getByTestId("ds-clear-yes").click();
  await expect(page.getByTestId("ds-empty")).toBeVisible();
  await expect(page.getByTestId("ds-total")).toHaveText("0");

  await page.getByTestId("ds-import-file").setInputFiles({ name: file.name, mimeType: "application/json", buffer: Buffer.from(file.text) });
  await expect(page.getByTestId("ds-import-summary")).toContainText("2 imported, 0 rejected");
  await expect(page.getByTestId("ds-total")).toHaveText("2");
  const after = await snap();
  expect(after).toEqual(before);
  await expect(page.getByTestId("ds-source-d1")).toHaveText("Imported (recorded)");
  await expect(page.getByTestId("ds-source-d2")).toHaveText("Imported (synthetic)");
  await expect(page.getByTestId("ds-count-source-imported")).toHaveText("2");
  await expect(page.getByTestId("ds-label-d1")).toHaveValue("human"); // the label survived as the user gave it
  await expect(page.getByTestId("ds-label-d2")).toBeEnabled(); // imported: no longer "generated here", so editable
  await page.getByTestId("ds-view-d2").click();
  await expect(page.getByTestId("ds-detail-synthetic")).toContainText("checked by regenerating");
});

