test("hostile and malformed files are refused with readable messages and change nothing", async ({ page }) => {
  await fill(page);
  const file = await download(page, () => page.getByTestId("ds-export").click());
  const good = JSON.parse(file.text) as { records: { session: { events: Record<string, unknown>[] }; source: { synthetic?: Record<string, unknown> } }[]; [k: string]: unknown };
  const feed = (content: string | Buffer) => page.getByTestId("ds-import-file").setInputFiles({ name: "x.json", mimeType: "application/json", buffer: Buffer.from(content) });
  const refused = async (content: string | Buffer, message: RegExp) => {
    await feed(content);
    await expect(page.getByTestId("ds-notice")).toContainText(message);
    await expect(page.getByTestId("ds-notice")).toHaveAttribute("role", "alert");
    await expect(page.getByTestId("ds-total")).toHaveText("2");
  };
  await refused("{nope", /not valid JSON/);
  await refused(JSON.stringify({ ...good, version: 2 }), /Unsupported format version/);
  await refused(JSON.stringify({ ...good, schema: "other" }), /Unsupported file format/);
  await refused(JSON.stringify({ ...good, extra: 1 }), /unknown field/);
  await refused(file.text.replace('"records"', '"__proto__": {"x": 1}, "records"'), /forbidden key/);
  await refused("[".repeat(100) + "]".repeat(100), /nested too deeply/);
  await refused(Buffer.alloc(26 * 1024 * 1024, 32), /too large/);

  // A forged synthetic session: the events are not what the generator makes for that profile and seed.
  const forged = JSON.parse(file.text) as typeof good;
  forged.records[1]!.session.events[1]!["t"] = (forged.records[1]!.session.events[1]!["t"] as number) + 0.5;
  await feed(JSON.stringify(forged));
  await expect(page.getByTestId("ds-import-rejected")).toContainText("Synthetic provenance inconsistent");
  await expect(page.getByTestId("ds-total")).toHaveText("3"); // the valid recorded one was imported (renamed); the forged one was not

  // A typing session must hold key classes only.
  await page.goto("/compare?captcha=text&seed=31&variant=clean&difficulty=medium");
  await page.getByTestId("text-answer").click();
  await page.keyboard.type("abc");
  await page.getByTestId("verify").click();
  await page.getByTestId("add-recorded").click();
  const typed = await download(page, async () => {
    await page.getByTestId("add-recorded-open").click();
    await page.getByTestId("ds-export").click();
  });
  const text = JSON.parse(typed.text) as typeof good;
  const keyed = text.records.find((r) => r.session.events.some((e) => e["code"] === "Letter"))!;
  expect(JSON.stringify(keyed.session.events)).not.toMatch(/Key[A-Z]/);
  keyed.session.events.find((e) => e["code"] === "Letter")!["code"] = "KeyQ";
  await feed(JSON.stringify(text));
  await expect(page.getByTestId("ds-import-rejected")).toContainText("never which key was typed");
});

test("signals and the classifier reading are recomputed on import, not trusted", async ({ page }) => {
  await fill(page, false);
  const file = await download(page, () => page.getByTestId("ds-export").click());
  const json = JSON.parse(file.text) as { records: { features: { values: Record<string, number | null> }; classifier: { result: string } }[] };
  const before = await page.getByTestId("ds-classifier-d1").getAttribute("data-label");
  json.records[0]!.features.values["reactionTime"] = 999999;
  json.records[0]!.classifier.result = before === "synthetic-like" ? "human-like" : "synthetic-like";
  await page.getByTestId("ds-clear").click();
  await page.getByTestId("ds-clear-yes").click();
  await page.getByTestId("ds-import-file").setInputFiles({ name: "t.json", mimeType: "application/json", buffer: Buffer.from(JSON.stringify(json)) });
  await expect(page.getByTestId("ds-import-differing")).toContainText("d1 features");
  expect(await page.getByTestId("ds-classifier-d1").getAttribute("data-label")).toBe(before);
  await page.getByTestId("ds-view-d1").click();
  await expect(page.getByTestId("ds-feat-reactionTime")).not.toContainText("1000.00 s");
  await expect(page.getByTestId("ds-claimed-classifier")).toContainText("not trusted");
});

